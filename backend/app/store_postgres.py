"""Durable PostgreSQL payment storage for Vercel.

All payment state mutations are atomic. Row locks serialize updates to an
invoice; unique event references make repeated webhooks idempotent.
"""
import secrets
import time
from .store import utcnow, add_months
from . import config


def connect():
    try:
        import psycopg
        from psycopg.rows import dict_row
    except ImportError as exc:
        raise RuntimeError('PostgreSQL selected: install psycopg[binary]') from exc
    return psycopg.connect(config.DATABASE_URL, row_factory=dict_row, connect_timeout=10)


def init_db():
    with connect() as db:
        db.execute('''CREATE TABLE IF NOT EXISTS orders (
           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
           token TEXT NOT NULL UNIQUE,
           member_name TEXT NOT NULL,
           months INTEGER NOT NULL,
           amount BIGINT NOT NULL,
           status TEXT NOT NULL DEFAULT 'UNPAID',
           has_exception INTEGER NOT NULL DEFAULT 0,
           paid_at TEXT,
           membership_start TEXT,
           membership_until TEXT,
           created_at TEXT NOT NULL
        )''')
        db.execute('''CREATE TABLE IF NOT EXISTS attempts (
           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
           order_id BIGINT NOT NULL REFERENCES orders(id),
           provider TEXT NOT NULL,
           order_code BIGINT NOT NULL UNIQUE,
           status TEXT NOT NULL DEFAULT 'CREATING',
           payment_link_id TEXT,
           qr_payload TEXT,
           checkout_url TEXT,
           bank_bin TEXT,
           account_number TEXT,
           account_name TEXT,
           description TEXT,
           reference TEXT,
           created_at TEXT NOT NULL,
           last_checked_at TEXT,
           confirmed_at TEXT
        )''')
        db.execute('''CREATE TABLE IF NOT EXISTS events (
           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
           attempt_id BIGINT NOT NULL REFERENCES attempts(id),
           source TEXT NOT NULL,
           event_key TEXT NOT NULL UNIQUE,
           outcome TEXT NOT NULL,
           amount BIGINT,
           created_at TEXT NOT NULL
        )''')
        db.execute('''CREATE TABLE IF NOT EXISTS subscriptions (
           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
           order_id BIGINT NOT NULL UNIQUE REFERENCES orders(id),
           status TEXT NOT NULL,
           consent_at TEXT NOT NULL,
           cancelled_at TEXT
        )''')
        db.execute('''CREATE TABLE IF NOT EXISTS payment_anomalies (
           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
           attempt_id BIGINT NOT NULL REFERENCES attempts(id),
           event_key TEXT NOT NULL UNIQUE,
           reason TEXT NOT NULL,
           amount BIGINT,
           created_at TEXT NOT NULL
        )''')
        db.execute('CREATE INDEX IF NOT EXISTS idx_attempts_order ON attempts(order_id)')
        for name, kind in {
            'auth_digest':'TEXT', 'auth_expires_at':'TEXT', 'auth_requested_at':'TEXT',
            'auth_reference':'TEXT', 'declined_at':'TEXT', 'terms_amount':'BIGINT',
            'terms_frequency':'TEXT'
        }.items():
            db.execute(f'ALTER TABLE subscriptions ADD COLUMN IF NOT EXISTS {name} {kind}')
        for name,kind in {'subscription_id':'BIGINT','renewal_of_id':'BIGINT','billing_due_at':'TEXT'}.items():
            db.execute(f'ALTER TABLE orders ADD COLUMN IF NOT EXISTS {name} {kind}')
        db.execute('CREATE UNIQUE INDEX IF NOT EXISTS idx_renewal_parent ON orders(renewal_of_id)')


def find_order(db, token):
    return db.execute('SELECT * FROM orders WHERE token=%s', (token,)).fetchone()


def create_order(member_name, months, amount):
    token = secrets.token_urlsafe(24)
    with connect() as db:
        db.execute('INSERT INTO orders(token,member_name,months,amount,created_at) VALUES(%s,%s,%s,%s,%s)',
                   (token,member_name,months,amount,utcnow()))
    return token


def present_order(token):
    with connect() as db:
        order = find_order(db, token)
        if not order:
            return None
        attempts = db.execute('SELECT * FROM attempts WHERE order_id=%s ORDER BY id DESC', (order['id'],)).fetchall()
        safe_attempts = [
            {key: a[key] for key in ('id','provider','order_code','status','checkout_url','bank_bin',
                                    'account_number','account_name','description','reference',
                                    'created_at','confirmed_at')} | {'has_qr': bool(a['qr_payload'])}
            for a in attempts
        ]
        subscription_filter = 'id=%s' if order['subscription_id'] else 'order_id=%s'
        subscription_key = order['subscription_id'] or order['id']
        subscription = db.execute(f'''SELECT status,consent_at,cancelled_at,auth_requested_at,auth_expires_at,
                  auth_reference,declined_at,terms_amount,terms_frequency FROM subscriptions WHERE {subscription_filter}''',
                                  (subscription_key,)).fetchone()
        return {**order, 'attempts':safe_attempts,'subscription': subscription}


def new_attempt(token, provider):
    with connect() as db:
        order = db.execute('SELECT * FROM orders WHERE token=%s FOR UPDATE', (token,)).fetchone()
        if not order:
            raise ValueError('NOT_FOUND')
        if order['status'] == 'PAID':
            raise ValueError('ALREADY_PAID')
        previous = db.execute('SELECT * FROM attempts WHERE order_id=%s ORDER BY id DESC LIMIT 1',
                              (order['id'],)).fetchone()
        if previous and previous['status'] in ('CREATING', 'PENDING', 'UNKNOWN', 'PAID'):
            return previous, False
        for _ in range(8):
            code = int(time.time() * 1000) * 100 + secrets.randbelow(100)
            new_id = db.execute('''INSERT INTO attempts(order_id,provider,order_code,created_at)
                            VALUES(%s,%s,%s,%s) ON CONFLICT (order_code) DO NOTHING RETURNING id''',
                            (order['id'],provider,code,utcnow())).fetchone()
            if new_id:
                db.execute("UPDATE orders SET status='PENDING' WHERE id=%s", (order['id'],))
                return db.execute('SELECT * FROM attempts WHERE id=%s', (new_id['id'],)).fetchone(), True
        raise RuntimeError('Unable to allocate payment code')


def update_attempt(attempt_id, *, status, qr_payload=None, checkout_url=None, payment_link_id=None,
                   bank_bin=None, account_number=None, account_name=None, description=None):
    with connect() as db:
        r = db.execute('''UPDATE attempts SET status=%s, qr_payload=%s, checkout_url=%s,
                    payment_link_id=%s, bank_bin=%s, account_number=%s, account_name=%s,
                    description=%s WHERE id=%s AND status NOT IN ('PAID','FAILED','CANCELLED')''',
                    (status,qr_payload,checkout_url,payment_link_id,bank_bin,
                     account_number,account_name,description,attempt_id))
        return r.rowcount > 0


def mark_checked(attempt_id):
    with connect() as db:
        db.execute('UPDATE attempts SET last_checked_at=%s WHERE id=%s', (utcnow(),attempt_id))


def revive_pending_attempt(attempt_id, payment_link_id, checkout_url):
    with connect() as db:
        db.execute('''UPDATE attempts SET status='PENDING',
               payment_link_id=COALESCE(payment_link_id,%s),
               checkout_url=COALESCE(checkout_url,%s)
               WHERE id=%s AND status='UNKNOWN' ''', (payment_link_id,checkout_url,attempt_id))


def find_attempt_by_code(code):
    with connect() as db:
        return db.execute('SELECT * FROM attempts WHERE order_code=%s',(code,)).fetchone()


def recent_attempt_for_order(token):
    with connect() as db:
        o = find_order(db, token)
        if not o: return None
        return db.execute('SELECT * FROM attempts WHERE order_id=%s ORDER BY id DESC LIMIT 1',
                          (o['id'],)).fetchone()


def apply_event(order_code, *, outcome, amount, source, reference, payment_link_id=None):
    if outcome not in ('PAID','FAILED','CANCELLED','PENDING'):
        raise ValueError('INVALID_OUTCOME')
    with connect() as db:
        found = db.execute('SELECT order_id FROM attempts WHERE order_code=%s',(order_code,)).fetchone()
        if not found:
            return 'UNKNOWN_ORDER'
        order = db.execute('SELECT * FROM orders WHERE id=%s FOR UPDATE',(found['order_id'],)).fetchone()
        attempt = db.execute('SELECT * FROM attempts WHERE order_code=%s FOR UPDATE',(order_code,)).fetchone()
        anomaly = None
        if attempt['payment_link_id'] and attempt['payment_link_id'] != payment_link_id:
            anomaly = 'LINK_MISMATCH'
        if amount != order['amount'] and outcome == 'PAID':
            anomaly = 'AMOUNT_MISMATCH'
        event_key = f'{source}:{reference}' if reference else f'{source}:{order_code}:{outcome}'
        if anomaly:
            added = db.execute('''INSERT INTO payment_anomalies(attempt_id,event_key,reason,amount,created_at)
                VALUES(%s,%s,%s,%s,%s) ON CONFLICT (event_key) DO NOTHING RETURNING id''',
                (attempt['id'],event_key,anomaly,amount,utcnow())).fetchone()
            if not added:
                return 'DUPLICATE_ANOMALY'
            db.execute('UPDATE orders SET has_exception=1 WHERE id=%s',(order['id'],))
            return anomaly
        added = db.execute('''INSERT INTO events(attempt_id,source,event_key,outcome,amount,created_at)
            VALUES(%s,%s,%s,%s,%s,%s) ON CONFLICT (event_key) DO NOTHING RETURNING id''',
            (attempt['id'],source,event_key,outcome,amount,utcnow())).fetchone()
        if not added:
            return 'DUPLICATE'
        if outcome == 'PAID':
            if attempt['status'] == 'PAID':
                return 'DUPLICATE_VERIFIED_PAYMENT'
            db.execute('UPDATE attempts SET status=%s, reference=%s, confirmed_at=%s WHERE id=%s',
                       ('PAID',reference,utcnow(),attempt['id']))
            if order['status'] == 'PAID':
                db.execute('UPDATE orders SET has_exception=1 WHERE id=%s',(order['id'],))
                return 'EXTRA_PAYMENT'
            moment=utcnow()
            period_start=order['billing_due_at'] or moment
            db.execute('''UPDATE orders SET status='PAID', paid_at=%s, membership_start=%s,
                            membership_until=%s WHERE id=%s''',
                       (moment,period_start,add_months(period_start,order['months']),order['id']))
            return 'PAID'
        if attempt['status'] == 'PAID':
            return 'IGNORED_AFTER_PAID'
        db.execute('UPDATE attempts SET status=%s WHERE id=%s',(outcome,attempt['id']))
        if outcome in ('FAILED','CANCELLED') and order['status'] != 'PAID':
            db.execute("UPDATE orders SET status='UNPAID' WHERE id=%s",(order['id'],))
        return outcome


def _demo_momo_digest(code: str) -> str:
    import hashlib
    return hashlib.sha256(code.encode('utf-8')).hexdigest()




def ensure_demo_momo_subscription(token):
    # Classroom-only pre-linked MoMo sample. No live wallet authentication.
    with connect() as db:
        order=db.execute('SELECT * FROM orders WHERE token=%s FOR UPDATE',(token,)).fetchone()
        if not order or order['months']!=1 or order['status']=='PAID':
            raise ValueError('Only an unpaid monthly invoice can use the demo MoMo wallet')
        sub=db.execute('SELECT * FROM subscriptions WHERE order_id=%s FOR UPDATE',(order['id'],)).fetchone()
        if sub and sub['status'] in ('CANCELLED_DEMO','DECLINED_DEMO','PENDING_DEMO'):
            raise ValueError('An existing wallet authorization was cancelled, declined or remains pending')
        now=utcnow()
        ref='MOMO-LINKED-DEMO'
        if sub:
            db.execute('''UPDATE subscriptions SET status='ACTIVE_DEMO', consent_at=%s,
                auth_requested_at=%s, terms_amount=%s, terms_frequency='MONTHLY',
                auth_reference=%s, auth_expires_at=NULL, auth_digest=NULL,
                declined_at=NULL WHERE id=%s''',
                (now,now,order['amount'],ref,sub['id']))
        else:
            db.execute('''INSERT INTO subscriptions(order_id,status,consent_at,
                auth_requested_at,terms_amount,terms_frequency,auth_reference)
                VALUES (%s,%s,%s,%s,%s,%s,%s)''',
                (order['id'],'ACTIVE_DEMO',now,now,order['amount'],'MONTHLY',ref))
    return present_order(token)


def demo_momo_start(token):
    from datetime import datetime, timezone, timedelta
    nonce=secrets.token_urlsafe(32)
    now=datetime.now(timezone.utc)
    expires=(now+timedelta(minutes=10)).isoformat(timespec='seconds')
    with connect() as db:
        order=db.execute('SELECT * FROM orders WHERE token=%s FOR UPDATE',(token,)).fetchone()
        if not order or order['months']!=1 or order['status']=='PAID':
            raise ValueError('Only an unpaid monthly invoice can start MoMo authorization')
        latest=db.execute('SELECT status FROM attempts WHERE order_id=%s ORDER BY id DESC LIMIT 1',(order['id'],)).fetchone()
        if latest and latest['status'] in ('CREATING','PENDING','UNKNOWN','PAID'):
            raise ValueError('Resolve the existing payment attempt before linking MoMo')
        sub=db.execute('SELECT * FROM subscriptions WHERE order_id=%s FOR UPDATE',(order['id'],)).fetchone()
        if sub and sub['status']=='ACTIVE_DEMO':raise ValueError('MoMo authorization is already active')
        if sub and sub['status']=='CANCELLED_DEMO':raise ValueError('This authorization was cancelled; create a new membership enrollment')
        if sub:
            db.execute('''UPDATE subscriptions SET status='PENDING_DEMO',consent_at='',auth_requested_at=%s,
                auth_expires_at=%s,auth_digest=%s,terms_amount=%s,terms_frequency='MONTHLY',
                cancelled_at=NULL,declined_at=NULL,auth_reference=NULL WHERE id=%s''',
                (now.isoformat(timespec='seconds'),expires,_demo_momo_digest(nonce),order['amount'],sub['id']))
        else:
            db.execute('''INSERT INTO subscriptions(order_id,status,consent_at,auth_requested_at,
                auth_expires_at,auth_digest,terms_amount,terms_frequency) VALUES(%s,%s,%s,%s,%s,%s,%s,%s)''',
                (order['id'],'PENDING_DEMO','',now.isoformat(timespec='seconds'),expires,
                 _demo_momo_digest(nonce),order['amount'],'MONTHLY'))
    return nonce


def demo_momo_session(token, nonce):
    from datetime import datetime, timezone
    with connect() as db:
        order=find_order(db,token)
        if not order: raise ValueError('Invoice not found')
        sub=db.execute('SELECT * FROM subscriptions WHERE order_id=%s',(order['id'],)).fetchone()
        if not sub or not sub['auth_digest'] or not secrets.compare_digest(_demo_momo_digest(nonce),sub['auth_digest']):
            raise ValueError('Invalid demo authorization link')
        if sub['status']=='PENDING_DEMO' and datetime.fromisoformat(sub['auth_expires_at'])<=datetime.now(timezone.utc):
            raise ValueError('This demo authorization link expired; restart from FitFlow')
        return {'status':sub['status'],'amount':order['amount'],'member_name':order['member_name'],
                'expires_at':sub['auth_expires_at'],'reference':sub['auth_reference']}


def demo_momo_decide(token,nonce,approved):
    from datetime import datetime, timezone
    with connect() as db:
        order=db.execute('SELECT * FROM orders WHERE token=%s FOR UPDATE',(token,)).fetchone()
        if not order:raise ValueError('Invoice not found')
        sub=db.execute('SELECT * FROM subscriptions WHERE order_id=%s FOR UPDATE',(order['id'],)).fetchone()
        if not sub or not sub['auth_digest'] or not secrets.compare_digest(_demo_momo_digest(nonce),sub['auth_digest']):
            raise ValueError('Invalid demo authorization link')
        if sub['status']!='PENDING_DEMO':return sub['status']
        if datetime.fromisoformat(sub['auth_expires_at'])<=datetime.now(timezone.utc):
            raise ValueError('Demo authorization link expired')
        if approved:
            ref='MOMO-SIM-'+secrets.token_hex(5).upper()
            db.execute("UPDATE subscriptions SET status='ACTIVE_DEMO',consent_at=%s,auth_reference=%s WHERE id=%s",(utcnow(),ref,sub['id']))
            return 'ACTIVE_DEMO'
        db.execute("UPDATE subscriptions SET status='DECLINED_DEMO',declined_at=%s WHERE id=%s",(utcnow(),sub['id']))
        return 'DECLINED_DEMO'


def demo_momo_cancel(token):
    with connect() as db:
        order=db.execute('SELECT * FROM orders WHERE token=%s FOR UPDATE',(token,)).fetchone()
        if not order:
            raise ValueError('NOT_FOUND')
        sub=db.execute('SELECT * FROM subscriptions WHERE order_id=%s OR id=%s',
                       (order['id'],order['subscription_id'] or -1)).fetchone()
        if not sub:
            raise ValueError('NO_SUBSCRIPTION')
        if sub['status'] != 'CANCELLED_DEMO':
            db.execute('UPDATE subscriptions SET status=%s, cancelled_at=%s WHERE id=%s',
                       ('CANCELLED_DEMO',utcnow(),sub['id']))
    return present_order(token)

def demo_momo_next_cycle(token):
    new_token=secrets.token_urlsafe(24)
    with connect() as db:
        origin=db.execute('SELECT * FROM orders WHERE token=%s FOR UPDATE',(token,)).fetchone()
        if not origin or origin['status']!='PAID' or origin['months']!=1 or not origin['membership_until']:
            raise ValueError('Pay the current monthly invoice before simulating renewal')
        if origin['subscription_id']:
            sub=db.execute('SELECT * FROM subscriptions WHERE id=%s FOR UPDATE',(origin['subscription_id'],)).fetchone()
        else:
            sub=db.execute('SELECT * FROM subscriptions WHERE order_id=%s FOR UPDATE',(origin['id'],)).fetchone()
        if not sub or sub['status']!='ACTIVE_DEMO':
            raise ValueError('No active demo authorization for the next billing cycle')
        existing=db.execute('SELECT token FROM orders WHERE renewal_of_id=%s',(origin['id'],)).fetchone()
        if existing:return existing['token']
        created=db.execute('''INSERT INTO orders(token,member_name,months,amount,created_at,
            subscription_id,renewal_of_id,billing_due_at) VALUES(%s,%s,%s,%s,%s,%s,%s,%s)
            ON CONFLICT (renewal_of_id) DO NOTHING RETURNING token''',
            (new_token,origin['member_name'],1,sub['terms_amount'] or origin['amount'],utcnow(),
             sub['id'],origin['id'],origin['membership_until'])).fetchone()
        if created:return created['token']
        return db.execute('SELECT token FROM orders WHERE renewal_of_id=%s',(origin['id'],)).fetchone()['token']


